test("/fpfe off stops the emotes and is saved; /fpfe on resumes", function()
    local client = NewClient():login()
    client:slash("off")
    eq(Saved().enabled, false)
    client:feed(12037)
    eq(#client.sent, 0)
    client:slash("ON")
    client:feed(12037)
    eq(#client.sent, 1)
end)

